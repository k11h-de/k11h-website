"""Write k11h/static/css/pygments-<skin>.css.
The base style applies by default; the other one applies via OS preference
(unless the visitor forced a mode) or via the manual data-theme switch.
usage: python themes/gen-pygments.py <skin> <light-style> <dark-style> <light|dark default>"""
import sys
from pathlib import Path
from pygments.formatters import HtmlFormatter

skin, light, dark, default = sys.argv[1:5]
other = "dark" if default == "light" else "light"
base_style, alt_style = (light, dark) if default == "light" else (dark, light)
defs = lambda style, prefix: HtmlFormatter(style=style).get_style_defs(prefix)
css = ("\n".join(l for l in (f"/* generated by gen-pygments.py: {light} / {dark}, default {default} */\n"
       + defs(base_style, ".highlight") + "\n"
       + defs(alt_style, f':root[data-theme="{other}"] .highlight') + "\n"
       + f"@media (prefers-color-scheme: {other}) {{\n"
       + defs(alt_style, f':root:not([data-theme="{default}"]) .highlight') + "\n}\n").splitlines() if not l.startswith("pre {")) + "\n")
out = Path(__file__).parent / "k11h/static/css" / f"pygments-{skin}.css"
out.write_text(css)
print(out.name, len(css))
